res1 = count_letters(main_str) #вызываем первую функцию и получаем количество каждой буквы
res2 = calculate_frequency(res1) #передаем результат во вторую функцию и получаем частоты

for l, f in res2.items(): #перебираем буквы "l" и их частоты "f"
    print(f"{l}: {f:.2f}") #выводим букву и ее частоту, округленную до 2 знаков после запятой
